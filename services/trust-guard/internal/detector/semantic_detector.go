package detector

import (
	"context"
	"fmt"
	"strings"

	"github.com/gursimransw/BearBreach/services/trust-guard/internal/clients"
	"github.com/gursimransw/BearBreach/services/trust-guard/internal/types"
)

// SemanticDetector sends an artifact to the Python Semantic Detector service
// and converts its response into a Trust Guard detection component result.
//
// A failed analysis returns an error rather than treating the artifact as benign.
func SemanticDetector(
	ctx context.Context,
	requestID string,
	targetString string,
	scanContext types.ScanContext,
	policyConfig *types.PolicyConfig,
	client types.SemanticDetectorClient,
) (types.DetectionComponentResult, error) {

	result := types.DetectionComponentResult{
		ComponentName:      "Semantic Detector",
		Score:              0,
		Findings:           []types.EventFinding{},
		ConstraintViolated: false,
	}

	// Ensure the policy configuration is available.
	if policyConfig == nil {
		return result, fmt.Errorf("semantic detector: policy configuration is nil")
	}

	policy := policyConfig.SemanticDetectorPolicy

	// Skip semantic analysis when the detector is disabled.
	if !policy.Enabled {
		return result, nil
	}

	// Validate the configured operating mode.
	mode := strings.ToLower(policy.Mode)

	if mode != "observation" && mode != "enforcement" {
		return result, fmt.Errorf(
			"semantic detector: unsupported mode %q",
			policy.Mode,
		)
	}

	// Ensure the configured risk contribution is within the allowed range.
	if policy.Weight < 0 || policy.Weight > 1 {
		return result, fmt.Errorf(
			"semantic detector: weight must be between 0 and 1",
		)
	}

	// The request ID is used to correlate analysis across both services.
	if strings.TrimSpace(requestID) == "" {
		return result, fmt.Errorf(
			"semantic detector: request ID is required",
		)
	}

	// Construct the request using the original artifact and scan context.
	request := types.SemanticDetectorRequest{
		RequestID:     requestID,
		TenantID:      scanContext.TenantID,
		ApplicationID: scanContext.ApplicationID,
		ArtifactType:  scanContext.ArtifactType,
		Text:          targetString,
	}

	// The HTTP client handles communication, timeouts, JSON decoding,
	// response validation and service failures.
	response, err := clients.Analyze(ctx, client, request)

	if err != nil {
		return result, fmt.Errorf(
			"semantic detector analysis failed: %w",
			err,
		)
	}

	// A completed analysis with no detection produces no finding or score.
	if !response.Result.Detected {
		return result, nil
	}

	// Determine whether the semantic finding contributes to enforcement.
	// Observation mode records the finding without affecting the risk score.
	weight := 0.0

	if mode == "enforcement" {
		weight = float64(policy.Weight)
	}

	// Create a finding for the detected semantic attack.
	// FindingID is assigned later by the central event aggregation logic.
	// RuleID remains empty because this finding was generated by an ML model.
	finding := types.EventFinding{
		FindingType:      "semantic_detection",
		Category:         response.Result.PredictedCategory,
		Title:            "Potential semantic attack detected",
		RiskContribution: weight,
		Detector: types.Detector{
			Service:    "semantic-detector",
			DetectorID: "semantic-similarity",
			Version:    response.DetectorVersion,
		},
	}

	// Store the finding regardless of the operating mode.
	result.Findings = []types.EventFinding{finding}

	// Only enforcement mode contributes to Trust Guard's aggregate risk score.
	result.Score = weight

	// Semantic detection is a scored signal, not a hard policy violation.
	result.ConstraintViolated = false

	return result, nil
}
